// Roman provinces at Trajanic maximum extent (ca. 117 CE)
// Province polygon data from the Digital Atlas of the Roman Empire (DARE),
// University of Lund (dare.ht.lu.se), via github.com/klokantech/roman-empire.
// Coordinates simplified with Douglas-Peucker (ε=0.1°). Format: [lat, lng].

export interface RomanProvince {
  name: string;
  nameEs?: string;
  desc: string;
  polygons: [number, number][][]; // array of outer rings (MultiPolygon)
}

// Ray-casting point-in-polygon. ring[i] = [lat, lng].
function pointInRing(lat: number, lng: number, ring: [number, number][]): boolean {
  let inside = false;
  const n = ring.length;
  for (let i = 0, j = n - 1; i < n; j = i++) {
    const yi = ring[i][0], xi = ring[i][1];
    const yj = ring[j][0], xj = ring[j][1];
    if ((yi > lat) !== (yj > lat)) {
      const xInt = (xj - xi) * (lat - yi) / (yj - yi) + xi;
      if (lng < xInt) inside = !inside;
    }
  }
  return inside;
}

// Province contains point if ANY of its rings contains it.
function provinceContains(lat: number, lng: number, prov: RomanProvince): boolean {
  return prov.polygons.some(ring => pointInRing(lat, lng, ring));
}

// Shoelace area (square degrees) for a single ring.
function ringArea(ring: [number, number][]): number {
  let a = 0;
  const n = ring.length;
  for (let i = 0, j = n - 1; i < n; j = i++) {
    a += ring[j][1] * ring[i][0] - ring[i][1] * ring[j][0];
  }
  return Math.abs(a) / 2;
}

function provinceArea(prov: RomanProvince): number {
  return prov.polygons.reduce((sum, ring) => sum + ringArea(ring), 0);
}

